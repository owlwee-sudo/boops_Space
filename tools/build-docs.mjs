// Regenerates knowledge/relationships.md and knowledge/sources.md from knowledge/data/*.json.
// Usage: node tools/build-docs.mjs   (also checks that every id resolves)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "knowledge");
const load = (f) => JSON.parse(readFileSync(join(root, "data", f), "utf8"));
const sources = load("sources.json"), nodes = load("nodes.json"), edges = load("edges.json");

const src = Object.fromEntries(sources.map((s) => [s.id, s]));
const node = Object.fromEntries(nodes.map((n) => [n.id, n]));

// ---- integrity check
const problems = [];
for (const n of nodes) for (const s of n.sources) if (!src[s]) problems.push(`node ${n.id}: unknown source ${s}`);
for (const e of edges) {
  for (const id of [e.from, e.to]) if (!node[id]) problems.push(`edge ${e.from}->${e.to}: unknown node ${id}`);
  for (const s of e.sources) if (!src[s]) problems.push(`edge ${e.from}->${e.to}: unknown source ${s}`);
}
const used = new Set([...nodes.flatMap((n) => n.sources), ...edges.flatMap((e) => e.sources)]);
for (const s of sources) if (!used.has(s.id)) problems.push(`source ${s.id} is not linked to any node or edge`);
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }

// ---- helpers
const EVI = { H: "🧑", A: "🐭", C: "🧫" };
const VERDICT = { good: "🟢", caution: "🟡", weak: "🔴", early: "🔵" };
const stars = (n) => (n ? "⭐".repeat(n) : "");
const evi = (s) => s.split("").map((c) => EVI[c]).join("");
const cite = (ids) => (ids.length ? ids.map((i) => `[${i}]`).join(" ") : "⚠️ no source yet");
const lbl = (id) => node[id].label;
const line = (e) =>
  `- **${lbl(e.from)} → ${lbl(e.to)}**: ${e.label}` +
  (e.evidence || e.stars ? ` · ${evi(e.evidence)}${stars(e.stars)}` : "") +
  ` · ${cite(e.sources)}` + (e.note ? `  \n  ${e.note}` : "");

const header = "<!-- GENERATED by tools/build-docs.mjs from knowledge/data/*.json — edit the JSON, then re-run. -->\n\n";

// ---- relationships.md
let r = header + "# Relationship list\n\n";
r += `${nodes.length} concepts · ${edges.length} links · ${sources.length} sources. ` +
  "Evidence: 🧑 humans · 🐭 animals · 🧫 cells · ⭐ to ⭐⭐⭐ strength. " +
  "Signal quality: 🟢 good · 🟡 use with care · 🔴 weak · 🔵 early. `[id]` = entry in [sources.md](sources.md).\n";
for (const [layer, title] of [["core", "Core web"], ["nervous", "Nervous system extension"]]) {
  r += `\n## ${title}\n`;
  for (const [type, head] of [["causal", "Causes"], ["amplifies", "Amplifies"], ["protects", "Protects"], ["confounds", "Confounds"], ["measures", "Measures"]]) {
    const list = edges.filter((e) => e.layer === layer && e.type === type);
    if (!list.length) continue;
    r += `\n### ${head} (${list.length})\n\n`;
    if (type === "measures") {
      r += list.map((e) => `- ${VERDICT[node[e.from].signal_verdict] ?? "▫️"} **${lbl(e.from)} → ${lbl(e.to)}**: ${e.label} · ${cite(e.sources)}`).join("\n") + "\n";
    } else r += list.map(line).join("\n") + "\n";
  }
}
r += "\n## Concepts\n\n| id | Concept | Category | Layer | What it is |\n|---|---|---|---|---|\n" +
  nodes.map((n) => `| \`${n.id}\` | ${n.label} | ${n.category}${n.signal_verdict ? " " + VERDICT[n.signal_verdict] : ""} | ${n.layer} | ${n.description.replace(/\|/g, "/")} |`).join("\n") + "\n";
writeFileSync(join(root, "relationships.md"), r);

// ---- sources.md
let s = header + "# Sources\n\nEvery resource used must be cited (Space Apps rule). `id` is how the data files and [relationships.md](relationships.md) refer to each source.\n";
for (const g of [...new Set(sources.map((x) => x.group))]) {
  s += `\n## ${g}\n\n` + sources.filter((x) => x.group === g).map((x) => `- \`${x.id}\` — [${x.title}](${x.url})`).join("\n") + "\n";
}
writeFileSync(join(root, "sources.md"), s);
console.log(`OK: ${nodes.length} nodes, ${edges.length} edges, ${sources.length} sources`);
